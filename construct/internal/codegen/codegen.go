const header = `/* eslint-disable */
// Code generated by ` + "`construct codegen`" + `; DO NOT EDIT.
//
// TypeScript mirror of the Construct wire schema. The Go structs in
// construct/schema (+ schema/primitives) are the single source of truth; this
// file is regenerated by ` + "`go run ./cmd/construct codegen`" + ` and checked for
// drift by ` + "`go run ./cmd/construct codegen --check`" + `. Edit the Go schema, not
// this file. See construct/construct.frozen.kvx for the frozen vocabulary.
`

// Generate produces the full TypeScript file as a deterministic byte-stable
// string.
func Generate() (string, error) {
	enumNames := map[string]bool{}
	for _, e := range enums() {
		enumNames[e.name] = true
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n")

	for _, e := range enums() {
		b.WriteString(emitEnum(e))
		b.WriteString("\n")
	}
	for _, t := range structs() {
		s, err := emitStruct(t, enumNames)
		if err != nil {
			return "", err
		}
		b.WriteString(s)
		b.WriteString("\n")
	}
	return b.String(), nil
}

// emitEnum renders one string-literal union, one value per line for stable,
// readable output.
func emitEnum(e enumDef) string {
	var b strings.Builder
	fmt.Fprintf(&b, "export type %s =\n", e.name)
	for _, v := range e.values {
		fmt.Fprintf(&b, "  | '%s'\n", v)
	}
	return b.String()
}

// emitStruct renders one Go struct as a TS interface.
func emitStruct(t reflect.Type, enumNames map[string]bool) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "export interface %s {\n", t.Name())
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		name, optional, skip := jsonField(f)
		if skip {
			continue
		}
		ts, err := tsType(f.Type, enumNames)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", t.Name(), f.Name, err)
		}
		q := ""
		if optional {
			q = "?"
		}
		fmt.Fprintf(&b, "  %s%s: %s\n", name, q, ts)
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// jsonField extracts the JSON name, optionality, and skip flag from a struct
// field. A field is optional when it has `omitempty` or is a pointer.
func jsonField(f reflect.StructField) (name string, optional, skip bool) {
	tag := f.Tag.Get("json")
	if tag == "-" {
		return "", false, true
	}
	parts := strings.Split(tag, ",")
	name = parts[0]
	if name == "" {
		name = f.Name
	}
	for _, p := range parts[1:] {
		if p == "omitempty" {
			optional = true
		}
	}
	if f.Type.Kind() == reflect.Ptr {
		optional = true
	}
	return name, optional, false
}

// tsType maps a Go type to its TypeScript representation.
func tsType(t reflect.Type, enumNames map[string]bool) (string, error) {
	// Named enum types (e.g. Kind, Stakes) render as their union type name.
	if t.Name() != "" && enumNames[t.Name()] {
		return t.Name(), nil
	}
	switch t.Kind() {
	case reflect.Ptr:
		return tsType(t.Elem(), enumNames)
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Slice:
		elem, err := tsType(t.Elem(), enumNames)
		if err != nil {
			return "", err
		}
		return elem + "[]", nil
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("unsupported map key %s", t.Key().Kind())
		}
		elem, err := tsType(t.Elem(), enumNames)
		if err != nil {
			return "", err
		}
		return "Record<string, " + elem + ">", nil
	case reflect.Interface:
		// An empty interface (interface{}/any) is an opaque payload (e.g. a
		// Frame's Fields); the safe TS mirror is `unknown`.
		if t.NumMethod() == 0 {
			return "unknown", nil
		}
		return "", fmt.Errorf("unsupported non-empty interface %s", t.Name())
	case reflect.Struct:
		if t.Name() == "" {
			return "", fmt.Errorf("anonymous struct unsupported")
		}
		return t.Name(), nil
	default:
		return "", fmt.Errorf("unsupported kind %s", t.Kind())
	}
}

