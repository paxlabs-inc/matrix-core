// Package codegen emits the TypeScript mirror of the Construct Go schema
// (schema + schema/primitives) into the client. The Go structs are the single
// source of truth (§1 decision 3: the daemon emits, the client only consumes);
// this package walks them by reflection and produces a deterministic,
// byte-stable .ts file with a --check mode for CI drift detection.
package codegen

