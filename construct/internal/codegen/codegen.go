// DefaultOutPath is where the generated TS lands, relative to the construct
// module root (the client repo is the sibling directory).
const DefaultOutPath = "../client/lib/construct/types.gen.ts"

// enumDef is a Go string-enum type rendered as a TS string-literal union.
type enumDef struct {
	name   string
	values []string
}

// enums lists every Construct enum, in deterministic emit order. Values are
// read from the Go consts so a rename is a compile error here (authoritative,
// never drifts from the schema).
func enums() []enumDef {
	return []enumDef{
		{"Kind", kindStrings(schema.Kinds)},
		{"Stakes", stakesStrings(schema.StakesValues)},
		{"Temporality", temporalityStrings(schema.TemporalityValues)},
		{"NarrationRole", []string{
			string(primitives.NarrationThinking),
			string(primitives.NarrationIntent),
			string(primitives.NarrationAnswer),
		}},
		{"Trend", []string{
			string(primitives.TrendUp),
			string(primitives.TrendDown),
			string(primitives.TrendFlat),
		}},
		{"MetricDisplay", metricDisplayStrings(primitives.MetricDisplayValues)},
		{"AffordanceKind", []string{
			string(primitives.AffordanceLink),
			string(primitives.AffordanceAsk),
			string(primitives.AffordanceCopy),
		}},
		{"Shape", shapeStrings(primitives.ShapeValues)},
		{"StepStatus", stepStatusStrings(primitives.StepStatusValues)},
		{"MediaKind", []string{
			string(primitives.MediaImage),
			string(primitives.MediaVideo),
			string(primitives.MediaAudio),
			string(primitives.MediaPage),
			string(primitives.MediaChart),
		}},
		{"ChartKind", chartKindStrings(primitives.ChartKindValues)},
		{"AskKind", askKindStrings(primitives.AskKindValues)},
	}
}

